const fs = require('node:fs');
const path = require('node:path');
const { root, read, scripts, styles, content } = require('./site_source.cjs');

function build() {
  const data = content();
  for (const file of Object.values(data.assets)) {
    if (!fs.existsSync(path.join(root, file))) throw new Error(`Missing asset: ${file}`);
  }
  const write = (file, text) => {
    const destination = path.join(root, file);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, text);
  };

  // A single private scope preserves existing initialization order without
  // leaking feature state into the browser's global namespace.
  write(
    'assets/app.js',
    "// Generated by npm run build. Edit src/scripts instead.\n(() => {\n'use strict';\n" +
      scripts() +
      '\n})();\n'
  );
  write('assets/site.css', styles());
  write(
    'assets/site-data.js',
    '// Generated by npm run build. Edit src/content/site.json instead.\nwindow.NOVA_DATA = ' +
      JSON.stringify(data) +
      ';\n'
  );
  write('index.html', read('src/index.html'));
  // The public CMS loader is small; the authentication SDK only loads in /admin/.
  const esbuild = require('esbuild');
  for (const [entry, outfile] of [['public', 'assets/cms-public.js'], ['admin', 'admin/admin.js']]) {
    esbuild.buildSync({ entryPoints: [path.join(root, 'src/cms/' + entry + '.js')], outfile: path.join(root, outfile), bundle: true, minify: true, platform: 'browser', target: 'es2022', legalComments: 'eof' });
  }
  write('admin/index.html', read('src/cms/admin.html'));
  write('admin/admin.css', read('src/cms/admin.css'));

  const aliases = {
    shop: 'shop',
    'shop/digestive-tonic': 'product/digestive',
    'shop/immunity-tonic': 'product/immunity',
    'shop/immunity-broth-kit': 'product/broth',
    about: 'story',
    contact: 'contact',
    journal: 'journal',
    'journal/coming-soon-stay-tuned': 'journal/post'
  };
  for (const [directory, route] of Object.entries(aliases)) {
    const link = '../'.repeat(directory.split('/').length) + '#/' + route;
    write(
      directory + '/index.html',
      '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Nova Health Synergy</title><meta http-equiv="refresh" content="0;url=' +
        link +
        '"><p><a href="' +
        link +
        '">Open Nova Health Synergy</a></p></html>'
    );
  }
  console.log(
    `Built index.html (${(Buffer.byteLength(read('index.html')) / 1024).toFixed(1)} KB), styles, scripts and content; ${Object.keys(data.assets).length} file-backed assets.`
  );
}

if (require.main === module) build();
module.exports = { build };
